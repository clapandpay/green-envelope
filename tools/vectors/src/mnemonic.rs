//! `mnemonic`: vectors for the 24-word wallet of `@ge/wallet` (clapandpay TASK-127).
//!
//! From a fixed PRF output to an address, every step outside `@ge/wallet`: the entropy by the
//! `hkdf` crate, the words and the BIP-39 seed by the `bip39` crate Klimper uses, and the keys
//! by chia-bls through `SecretKey::from_seed`, which is exactly how Sage imports a mnemonic
//! (`crates/sage/src/endpoints/keys.rs`: `SecretKey::from_seed(&mnemonic.to_seed(""))`).

use std::path::Path;

use anyhow::{Context, Result, anyhow};
use bip39::Mnemonic;
use chia_wallet_sdk::chia::bls::{SecretKey, master_to_wallet_unhardened};
use chia_wallet_sdk::chia::puzzle_types::DeriveSynthetic;
use chia_wallet_sdk::chia::puzzle_types::standard::StandardArgs;
use chia_wallet_sdk::prelude::*;
use hkdf::Hkdf;
use serde_json::{Value, json};
use sha2::Sha256;

/// HKDF `info` of the entropy; `MNEMONIC_INFO_TAG` in `packages/wallet/src/passkey.ts`.
const MNEMONIC_INFO: &[u8] = b"clapandpay:mnemonic:v2";

fn prf_outputs() -> Vec<[u8; 32]> {
    let mut counting = [0u8; 32];
    for (i, byte) in counting.iter_mut().enumerate() {
        *byte = u8::try_from(i).unwrap_or(0);
    }
    let mut stepped = [0u8; 32];
    for (i, byte) in stepped.iter_mut().enumerate() {
        *byte = u8::try_from(i)
            .unwrap_or(0)
            .wrapping_mul(37)
            .wrapping_add(11);
    }
    vec![[0u8; 32], [7u8; 32], [0xff; 32], counting, stepped]
}

fn address(puzzle_hash: Bytes32, prefix: &str) -> Result<String> {
    Ok(Address::new(puzzle_hash, prefix.to_string()).encode()?)
}

fn vector(prf: &[u8; 32]) -> Result<Value> {
    // HKDF-SHA256 with an empty salt, as WebCrypto's HKDF with `salt: new Uint8Array(0)`.
    let mut entropy = [0u8; 32];
    Hkdf::<Sha256>::new(Some(&[]), prf)
        .expand(MNEMONIC_INFO, &mut entropy)
        .map_err(|error| anyhow!("hkdf: {error}"))?;
    let mnemonic = Mnemonic::from_entropy(&entropy)?;
    let seed = mnemonic.to_seed("");
    let master_sk = SecretKey::from_seed(&seed);
    let master_pk = master_sk.public_key();
    // The first receive address of a standard Chia wallet: m/12381/8444/2/0, synthetic key.
    let wallet_pk = master_to_wallet_unhardened(&master_pk, 0);
    let puzzle_hash: Bytes32 = StandardArgs::curry_tree_hash(wallet_pk.derive_synthetic()).into();
    Ok(json!({
        "prf": hex::encode(prf),
        "entropy": hex::encode(entropy),
        "mnemonic": mnemonic.to_string(),
        "seed": hex::encode(seed),
        "master_pk": hex::encode(master_pk.to_bytes()),
        "fingerprint": master_pk.get_fingerprint(),
        "first_puzzle_hash": hex::encode(puzzle_hash),
        "first_address_xch": address(puzzle_hash, "xch")?,
        "first_address_txch": address(puzzle_hash, "txch")?,
    }))
}

pub fn run(out: &Path) -> Result<()> {
    let vectors = json!({
        "_comment": "Generated by tools/vectors (`cargo run -- mnemonic`) with hkdf, bip39 2.2.1 and chia-wallet-sdk 0.33.0. Do not edit.",
        "info": String::from_utf8_lossy(MNEMONIC_INFO),
        "wallets": prf_outputs().iter().map(vector).collect::<Result<Vec<_>>>()?,
    });
    let mut text = serde_json::to_string_pretty(&vectors)?;
    text.push('\n');
    std::fs::write(out, text).with_context(|| format!("cannot write {}", out.display()))?;
    println!("wrote {}", out.display());
    Ok(())
}
